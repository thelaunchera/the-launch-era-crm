import {cp,copyFile,mkdir,readFile,writeFile,rm} from "node:fs/promises";
import {resolve,join} from "node:path";
const output=resolve(".customer-site");
await rm(output,{recursive:true,force:true});
await mkdir(join(output,"vendor"),{recursive:true});
for(const name of ["index.html","styles.css","app.js"])await copyFile(resolve("customer-crm",name),join(output,name));
await copyFile(resolve("vendor/supabase-js-v2.57.0.umd.js"),join(output,"vendor/supabase-js-v2.57.0.umd.js"));
const index=join(output,"index.html");
const html=await readFile(index,"utf8");
if(!html.includes("../vendor/supabase-js-v2.57.0.umd.js"))throw Error("Safe customer library path anchor missing");
await writeFile(index,html.replace("../vendor/supabase-js-v2.57.0.umd.js","./vendor/supabase-js-v2.57.0.umd.js"));
await writeFile(join(output,".nojekyll"),"");
await writeFile(join(output,"robots.txt"),"User-agent: *\nDisallow: /\n");
console.log("Customer-only artifact built; owner source is not copied.");

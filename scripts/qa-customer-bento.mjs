import assert from "node:assert/strict";
import {readFileSync,readdirSync} from "node:fs";
const root=".bento-preview";
assert.deepEqual(readdirSync(root).sort(),["features-bento.css","features-bento.js","index.html","robots.txt"].sort());
const html=readFileSync(root+"/index.html","utf8"),css=readFileSync(root+"/features-bento.css","utf8"),js=readFileSync(root+"/features-bento.js","utf8");
new Function(js);
const tiles=[...html.matchAll(/class="bento-tile/g)];
assert.equal(tiles.length,7,"Expected seven distinct tiles");
for(const component of ["tile-headline","tile-accent","tile-donut","tile-bars","tile-flow","tile-sparkline","tile-activity"])assert.ok(html.includes(component),"Missing "+component);
assert.match(css,/grid-template-columns:repeat\(4,minmax\(0,1fr\)\)/);
assert.match(css,/grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/);
assert.match(css,/gap:8px/);
assert.match(css,/border-radius:16px/);
assert.match(css,/scale\(\.6\)/);
assert.match(css,/calc\(var\(--i,0\) \* 80ms\)/);
assert.match(css,/@media\(prefers-reduced-motion:reduce\)/);
assert.match(js,/IntersectionObserver/);
assert.match(js,/observer\.disconnect\(\)/);
assert.ok(!/supabase|stripe|fetch\(|localStorage|sessionStorage|setInterval\(/i.test(js),"Promo motion must not access any data");
assert.ok(!/owner-dashboard|idea-vault|jessy-owner|tle_owner_ideas/i.test(html+css+js),"No owner modules in commercial page");
assert.match(html,/Illustrative|illustrative/);
console.log("PASS: safe, accessible, one-shot bento with isolated preview assets");

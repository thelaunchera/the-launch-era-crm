import {copyFile,mkdir,rm,writeFile,readFile} from "node:fs/promises";
import {resolve,join} from "node:path";
const dest=resolve(".bento-preview");
await rm(dest,{recursive:true,force:true});
await mkdir(dest,{recursive:true});
for(const name of ["features-bento.css","features-bento.js"])await copyFile(resolve("customer-crm",name),join(dest,name));
await copyFile(resolve("customer-crm/features-bento.html"),join(dest,"index.html"));
const html=await readFile(join(dest,"index.html"),"utf8");
if(!html.includes('name="robots" content="noindex,nofollow,noarchive"'))throw Error("Bento preview must not be indexed");
await writeFile(join(dest,"robots.txt"),"User-agent: *\nDisallow: /\n");
console.log("Isolated visual-only bento preview prepared; CRM data and owner modules excluded.");
